"""`mudi-emu reference check|refresh`: small copies of GL files, kept in the repo so they can be
read (and cited) without the image: reference/<image>/.

Each entry is either a verbatim copy of one file in the image, or something derived from it (a
directory listing, the CSS variables GL's theme defines). Nothing else from the image is ever
committed. `check` compares every entry with the extracted image; `refresh` rewrites them from it."""
import gzip, os, re

from . import images

# name -> (kind, source in the image)
SOURCES = {
    "e5800-4.10.0": {
        "abfota_update": ("file", "/usr/bin/abfota_update"),
        "gl-ngx-session.lua": ("file", "/usr/sbin/gl-ngx-session"),
        "gl.conf": ("file", "/etc/nginx/conf.d/gl.conf"),
        "oui_nginx.conf": ("file", "/etc/nginx/oui_nginx.conf"),
        "oui-lib-rpc.lua": ("file", "/usr/lib/lua/oui/rpc.lua"),
        "oui-lib-ubus.lua": ("file", "/usr/lib/lua/oui/ubus.lua"),
        "oui-rpc.lua": ("file", "/usr/share/gl-ngx/oui-rpc.lua"),
        "oui-ws.lua": ("file", "/usr/share/gl-ngx/oui-ws.lua"),
        "websocket-cellular.lua": ("file", "/usr/share/gl-ngx/websocket/cellular.lua"),
        "menu-cellular-detail.json": ("file", "/usr/share/oui/menu.d/cellular-detail.json"),
        "menu-internet.json": ("file", "/usr/share/oui/menu.d/internet.json"),
        "menu-views.txt": ("ls", "/usr/share/oui/menu.d"),
        "rpc-objects.txt": ("ls", "/usr/lib/oui-httpd/rpc"),
        "theme-vars.txt": ("theme-vars", "/www/theme"),
    },
}

THEME_HEAD = ("# CSS custom properties GL defines (www/theme/base.css + {default,classic,dark}/index.css.gz).\n"
              "# Generated by `mudi-emu reference refresh`; lint page CSS against it (a var() GL does not\n"
              "# define fails silently in the browser).\n")


def directory(img):
    return os.path.join(images.REPO, "reference", img["name"])


def _derive(img, kind, src):
    root = img["rootfs"]
    path = os.path.join(root, src.lstrip("/"))
    if kind == "file":
        with open(path, "rb") as f:
            return f.read()
    if kind == "ls":
        return "".join(n + "\n" for n in sorted(os.listdir(path))).encode()
    if kind == "theme-vars":
        with open(os.path.join(path, "base.css")) as f:
            css = f.read()
        for v in ("default", "classic", "dark"):
            css += gzip.open(os.path.join(path, v, "index.css.gz")).read().decode()
        names = sorted(set(re.findall(r"(--[A-Za-z0-9-]+)\s*:", css)))
        return (THEME_HEAD + "".join(n + "\n" for n in names)).encode()
    raise ValueError(kind)


def entries(img):
    if img["name"] not in SOURCES:
        raise SystemExit("no reference set for image %s" % img["name"])
    return SOURCES[img["name"]]


def check(img, verbose=True):
    """-> list of problems (empty = every copy matches the extracted image)."""
    from . import userland
    userland.have_rootfs(img)
    d, bad = directory(img), []
    want = entries(img)
    for name in sorted(set(os.listdir(d)) - set(want) - {"README.md"}):
        bad.append("%s: not in the source list (lib/mudi_emu/reference.py)" % name)
    for name, (kind, src) in sorted(want.items()):
        try:
            with open(os.path.join(d, name), "rb") as f:
                have = f.read()
        except OSError:
            bad.append("%s: missing" % name)
            continue
        if have != _derive(img, kind, src):
            bad.append("%s: differs from %s (%s)" % (name, src, kind))
    if verbose:
        print("\n".join(bad) if bad else "reference/%s: all %d entries match the image" % (img["name"], len(want)))
    return bad


def refresh(img):
    from . import userland
    userland.have_rootfs(img)
    d = directory(img)
    os.makedirs(d, exist_ok=True)
    for name, (kind, src) in sorted(entries(img).items()):
        path = os.path.join(d, name)
        with open(path, "wb") as f:
            f.write(_derive(img, kind, src))
        os.chmod(path, 0o644)                        # reading copies, never run from here
    print("refreshed reference/%s (%d entries)" % (img["name"], len(entries(img))))
